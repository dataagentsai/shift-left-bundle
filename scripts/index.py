"""Write catalog/INDEX.md: counts, what blocks at start, and every check with its Databricks binding.

    uv run scripts/index.py
"""
from collections import Counter
from pathlib import Path

import lint

ROOT = Path(__file__).resolve().parent.parent


def main():
    recs = lint.load_checks()
    fam = lint.load_vocab()["families"]
    bind = lint.load_bindings().get("databricks", {}).get("checks", {})
    gates = Counter(r["gate"] for r in recs)
    status = Counter(bind[r["id"]]["status"] for r in recs if r["id"] in bind)
    out = ["# Catalog index", "", "Generated by `uv run scripts/index.py`. Edit the YAML in `catalog/checks/`, not this file.", "",
           f"**{len(recs)} checks** in {len(fam)} families. Starting gates: "
           + ", ".join(f"{gates[g]} {g}" for g in ("block", "warn", "report")) + ".", "",
           "Databricks binding: " + ", ".join(f"{status[s]} {s}" for s in ("adopt", "cost", "build", "trial"))
           + " (adopt = off-the-shelf rule, cost = existing cost rule, build = we write it, trial = candidate tool).", "",
           "## Blocks from day one", "", "| Id | Title | Stage |", "|---|---|---|"]
    out += [f"| {r['id']} | {r['title']} | {r['stage']} |" for r in recs if r["gate"] == "block"]
    for f, meta in fam.items():
        rs = [r for r in recs if r["_file"] == f]
        out += ["", f"## {f}: {meta['name']} ({len(rs)})", "", meta["asks"], "",
                "| Id | Title | Level | Stage | Gate | DAC | Databricks tool | Status |", "|---|---|---|---|---|---|---|---|"]
        for r in rs:
            b = bind.get(r["id"], {})
            out.append(f"| {r['id']} | {r['title']} | {r['level']} | {r['stage']} | {r['gate']} | {', '.join(r['dac']) or '—'} "
                       f"| {b.get('tool', '—')}: {', '.join(map(str, b.get('rules', [])))} | {b.get('status', '—')} |")
    (ROOT / "catalog" / "INDEX.md").write_text("\n".join(out) + "\n")
    print(f"catalog/INDEX.md: {len(recs)} checks; gates {dict(gates)}; binding {dict(status)}")


if __name__ == "__main__":
    main()
